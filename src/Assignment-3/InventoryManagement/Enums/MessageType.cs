namespace InventoryManagement.Enums
{
    /// <summary>
    /// The MessageType Enum is used to display console message with specific colors based on the type of message.
    /// </summary>
    public enum MessageType
    {
        /// <summary>
        /// Represents a success message.
        /// </summary>
        Success,

        /// <summary>
        /// Represents a error message.
        /// </summary>
        Error,

        /// <summary>
        /// Represents an information message.
        /// </summary>
        Info,
    }
}