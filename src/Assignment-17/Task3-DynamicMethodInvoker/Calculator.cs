namespace DynamicMethodInvoker.Class
{
    /// <summary>
    /// Methods used for calculation purposes (Demonstration for Task 3).
    /// </summary>
    public class Calculator
    {
        /// <summary>
        /// Tells the user that the add function is invoked.
        /// </summary>
        public void Add()
        {
            Console.WriteLine("Add method invoked.");
        }

        /// <summary>
        /// Tells the user that the subtract function is invoked.
        /// </summary>
        public void Subtract()
        {
            Console.WriteLine("Subtract method invoked.");
        }

        /// <summary>
        /// Tells the user that the multiply function is invoked.
        /// </summary>
        public void Multiply()
        {
            Console.WriteLine("Multiply method invoked.");
        }
    }
}